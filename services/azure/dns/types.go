package dns

// Zone is the ARM resource shape for Microsoft.Network/dnsZones.
type Zone struct {
	ID         string            `json:"id"`
	Name       string            `json:"name"`
	Type       string            `json:"type"`
	Location   string            `json:"location"`
	Tags       map[string]string `json:"tags,omitempty"`
	Properties map[string]any    `json:"properties"`
}

// RecordSet is the ARM child resource shape for Microsoft.Network/dnsZones/{recordType}.
type RecordSet struct {
	ID         string         `json:"id"`
	Name       string         `json:"name"`
	Type       string         `json:"type"`
	Properties map[string]any `json:"properties"`
}
